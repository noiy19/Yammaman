#!/usr/bin/env node
/**
 * gen-eva-tokens.mjs — compile the vendored EVA theme JSON into CSS.
 *
 * WHY THIS EXISTS
 * The EVA design system is not authored in this repo. It is a *frozen upstream
 * artifact* (`@muen/dsh-eva-theme`, MIT) that lives inside the Mitsumeru
 * harness. Copying its ~400 tokens into CSS by hand guarantees drift: upstream
 * ships a token, we forget it, a surface silently falls back.
 *
 * So we vendor the source JSON verbatim (`design-system/eva/*.json`) and
 * *generate* the CSS from it. Re-running this script after dropping in a newer
 * upstream JSON is the whole upgrade path. `src/styles/eva.css` is a build
 * artifact that happens to be committed, so a diff on it is a reviewable,
 * intentional token change.
 *
 * LAYERING (do not collapse these)
 *   1. static  — `--dsw-static-*`  primitives. Raw hex. Brand-agnostic.
 *   2. alias   — `--dsw-alias-*`   semantics. Points at statics. THIS is the
 *                                  seam a brand kit is allowed to override.
 * The Yammaman brand kit (src/styles/brand-kit.css) only ever re-points
 * layer 2. It must never introduce new `--dsw-*` names.
 *
 * OUTPUT
 *   :root                    EVA 00 (light)  — static + alias
 *   [data-ds-dark-theme]     EVA 01 (dark)   — the same names, re-valued
 *
 * The dark selector matches how the harness switches themes — the ACTIVE theme
 * attribute, not the OS `prefers-color-scheme`. The Yammaman brand package uses
 * the same key, so the storefront and the DSH shell stay in step.
 *
 * Usage: node scripts/gen-eva-tokens.mjs [--check]
 *   --check  exit 1 if the committed CSS is stale (used by CI)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const EVA_DIR = join(ROOT, 'design-system', 'eva');
const OUT = join(ROOT, 'src', 'styles', 'eva.css');

const THEMES = [
  { id: 'eva-00', label: 'EVA 00 — light', selector: ':root' },
  { id: 'eva-01', label: 'EVA 01 — dark', selector: "[data-ds-dark-theme='true']" },
];

/** Group token names by their EVA tier so the output is readable. */
function tierOf(name) {
  if (name.startsWith('--dsw-static-')) return 'static';
  if (name.startsWith('--dsw-alias-')) return 'alias';
  if (name.startsWith('--dsw-specific-')) return 'specific';
  if (name.startsWith('--dsw-ctp-')) return 'ctp';
  return 'other';
}

const TIER_ORDER = ['static', 'alias', 'specific', 'ctp', 'other'];
const TIER_TITLE = {
  static: 'Layer 1 — static primitives (raw values; brand-agnostic)',
  alias: 'Layer 2 — alias semantics (the seam a brand kit overrides)',
  specific: 'Component-specific slots',
  ctp: 'Catppuccin accents',
  other: 'Ungrouped',
};

function readTheme(id) {
  const file = join(EVA_DIR, `${id}.json`);
  if (!existsSync(file)) throw new Error(`missing vendored theme: ${file}`);
  const json = JSON.parse(readFileSync(file, 'utf8'));
  if (!json.tokens || typeof json.tokens !== 'object') {
    throw new Error(`${id}.json has no .tokens object`);
  }
  return json;
}

function renderBlock(json, selector, indent) {
  const pad = ' '.repeat(indent);
  const byTier = new Map(TIER_ORDER.map((t) => [t, []]));
  for (const [name, value] of Object.entries(json.tokens)) {
    byTier.get(tierOf(name)).push([name, value]);
  }

  const lines = [`${selector} {`];
  for (const tier of TIER_ORDER) {
    const entries = byTier.get(tier);
    if (!entries.length) continue;
    entries.sort(([a], [b]) => a.localeCompare(b));
    lines.push(`${pad}/* ${TIER_TITLE[tier]} */`);
    for (const [name, value] of entries) lines.push(`${pad}${name}: ${value};`);
    lines.push('');
  }
  if (lines[lines.length - 1] === '') lines.pop();
  lines.push('}');
  return lines.join('\n');
}

function build() {
  const light = readTheme('eva-00');
  const dark = readTheme('eva-01');
  const upstream = JSON.parse(
    readFileSync(join(EVA_DIR, 'UPSTREAM-package.json'), 'utf8'),
  );

  const header = `/* ==========================================================================
 * eva.css — GENERATED FILE. DO NOT EDIT BY HAND.
 * ==========================================================================
 * Source:      @muen/dsh-eva-theme v${upstream.version} (MIT)
 * Generated by scripts/gen-eva-tokens.mjs — run \`pnpm run tokens:build\`.
 * CI verifies this file is current: \`node scripts/gen-eva-tokens.mjs --check\`.
 *
 * This is the FROZEN EVA FOUNDATION. It is upstream's design system, vendored
 * verbatim so the storefront renders identically to the harness and to any
 * future client.
 *
 *   Layer 1  --dsw-static-*   primitives    raw values, brand-agnostic
 *   Layer 2  --dsw-alias-*    semantics     the seam brands override
 *
 * Yammaman's palette lives in brand-kit.css and only re-points Layer 2.
 * If you are looking for a colour to use in a component: use the Tailwind
 * semantic utilities (bg-surface, text-primary, …) or an --dsw-alias-* var.
 * Never a --dsw-static-*, never a raw hex. The no-ad-hoc-values gate enforces
 * this and documents the few files allowed to hold raw values.
 * ========================================================================== */

`;

  const blocks = THEMES.map(({ selector }, i) => {
    const json = i === 0 ? light : dark;
    const note =
      i === 0
        ? '/* ---- EVA 00 (light) — the default theme ---- */'
        : '/* ---- EVA 01 (dark) — re-values the same names, adds none ---- */';
    return `${note}\n${renderBlock(json, selector, 2)}`;
  });

  return `${header}${blocks.join('\n\n')}\n`;
}

const css = build();

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== css) {
    console.error(
      'eva.css is STALE.\n' +
        'The vendored EVA JSON and the generated CSS disagree.\n' +
        'Run: pnpm run tokens:build',
    );
    process.exit(1);
  }
  console.log('eva.css is current.');
} else {
  writeFileSync(OUT, css);
  const count = (css.match(/^\s+--dsw-/gm) || []).length;
  console.log(`wrote src/styles/eva.css (${count} token declarations)`);
}
